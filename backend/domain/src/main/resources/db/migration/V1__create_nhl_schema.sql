CREATE TABLE current_season (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id VARCHAR(255) NOT NULL UNIQUE,
    season_display_name VARCHAR(255),
    is_active BOOLEAN,
    last_updated VARCHAR(255)
);

CREATE TABLE players (
    player_id BIGINT NOT NULL,
    season VARCHAR(8) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    position_code VARCHAR(255),
    team_code VARCHAR(255),
    team_logo_url VARCHAR(255),
    games_played INTEGER,
    goals INTEGER,
    assists INTEGER,
    points INTEGER,
    points_per_game DOUBLE PRECISION,
    plus_minus INTEGER,
    penalty_minutes INTEGER,
    power_play_goals INTEGER,
    shorthanded_goals INTEGER,
    game_winning_goals INTEGER,
    overtime_goals INTEGER,
    shots INTEGER,
    shooting_percentage DOUBLE PRECISION,
    current_point_streak INTEGER,
    current_pointless_streak INTEGER,
    points_per_lastngames DOUBLE PRECISION,
    hot BOOLEAN,
    cold BOOLEAN,
    last_updated TIMESTAMP(6),
    headshot_url VARCHAR(255),
    date VARCHAR(255),
    opponent_abbrev VARCHAR(255),
    home_road_flag VARCHAR(255),
    PRIMARY KEY (player_id, season)
);

CREATE TABLE teams (
    team_code VARCHAR(255) NOT NULL,
    season VARCHAR(255) NOT NULL,
    team_name VARCHAR(255) NOT NULL,
    franchise_name VARCHAR(255),
    logo_url VARCHAR(255),
    games_played INTEGER,
    wins INTEGER,
    losses INTEGER,
    overtime_losses INTEGER,
    points INTEGER,
    point_percentage DOUBLE PRECISION,
    goals_for INTEGER,
    goals_against INTEGER,
    goal_differential INTEGER,
    conference_name VARCHAR(255),
    division_name VARCHAR(255),
    current_win_streak INTEGER,
    current_loss_streak INTEGER,
    last10games_win_percentage DOUBLE PRECISION,
    last10games_point_percentage DOUBLE PRECISION,
    last10gamesppg DOUBLE PRECISION,
    hot BOOLEAN,
    cold BOOLEAN,
    point_streak BOOLEAN,
    next_opponent_code VARCHAR(255),
    next_game_date VARCHAR(255),
    next_game_is_home BOOLEAN,
    last_updated VARCHAR(255),
    PRIMARY KEY (season, team_code)
);

CREATE TABLE game_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL,
    game_id BIGINT NOT NULL,
    game_date VARCHAR(255) NOT NULL,
    opponent_team_code VARCHAR(255),
    home_game BOOLEAN,
    goals INTEGER,
    assists INTEGER,
    points INTEGER,
    plus_minus INTEGER,
    shots INTEGER,
    time_on_ice INTEGER,
    game_won BOOLEAN,
    season_id VARCHAR(255),
    game_number INTEGER
);

CREATE TABLE team_games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL,
    team_code VARCHAR(255) NOT NULL,
    game_date VARCHAR(255) NOT NULL,
    opponent_team_code VARCHAR(255),
    home_game BOOLEAN,
    goals_for INTEGER,
    goals_against INTEGER,
    won BOOLEAN,
    overtime_loss BOOLEAN,
    game_type VARCHAR(255),
    season_id VARCHAR(255),
    game_number INTEGER
);
